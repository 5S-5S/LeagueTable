let _teamLookupIndexCache = null;

function getTeamLookupIndex() {
    if (_teamLookupIndexCache) return _teamLookupIndexCache;
    const teamColors = getTeamColors();
    _teamLookupIndexCache = new Map();
    for (const league of Object.keys(teamColors)) {
        teamColors[league].forEach(entry => {
            const key = `${league}::${entry[0]}`;
            if (!_teamLookupIndexCache.has(key)) _teamLookupIndexCache.set(key, entry);
        });
    }
    return _teamLookupIndexCache;
}

function findTeamEntry(teamName, league) {
    const index = getTeamLookupIndex();
    if (league === 'champions-league') {
        const allLeagues = ['champions-league', 'premier-league', 'la-liga', 'serie-a', 'bundesliga', 'ligue-1'];
        for (const searchLeague of allLeagues) {
            const entry = index.get(`${searchLeague}::${teamName}`);
            if (entry) return entry;
        }
        return null;
    }
    return index.get(`${league}::${teamName}`) || null;
}

function getTeamColor(teamName, league) {
    const entry = findTeamEntry(teamName, league);
    return entry ? entry[1] : null;
}

function hexToRgb(hex) {
    const clean = hex.replace('#', '');
    const full = clean.length === 3 ? clean.split('').map(c => c + c).join('') : clean;
    return {
        r: parseInt(full.substring(0, 2), 16),
        g: parseInt(full.substring(2, 4), 16),
        b: parseInt(full.substring(4, 6), 16),
    };
}

function rgbToHex({ r, g, b }) {
    const clamp = c => Math.max(0, Math.min(255, Math.round(c)));
    return '#' + [r, g, b].map(c => clamp(c).toString(16).padStart(2, '0')).join('');
}

function relativeLuminance({ r, g, b }) {
    const channel = c => {
        const v = c / 255;
        return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    };
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

function contrastRatio(rgb1, rgb2) {
    const l1 = relativeLuminance(rgb1);
    const l2 = relativeLuminance(rgb2);
    const lighter = Math.max(l1, l2);
    const darker = Math.min(l1, l2);
    return (lighter + 0.05) / (darker + 0.05);
}

const DARK_MODE_BG_RGB = { r: 0x22, g: 0x22, b: 0x22 };

function ensureReadableOnDark(hex) {
    const rgb = hexToRgb(hex);
    if (contrastRatio(rgb, DARK_MODE_BG_RGB) >= 4.5) return hex;
    for (let t = 0.1; t <= 1; t += 0.1) {
        const mixed = {
            r: rgb.r + (255 - rgb.r) * t,
            g: rgb.g + (255 - rgb.g) * t,
            b: rgb.b + (255 - rgb.b) * t,
        };
        if (contrastRatio(mixed, DARK_MODE_BG_RGB) >= 4.5) return rgbToHex(mixed);
    }
    return '#ffffff';
}

function pickTeamTextColor(rawColor, cssClass) {
    if (!rawColor) return rawColor;
    if (cssClass === 'team1-highlight' || cssClass === 'team2-highlight') return rawColor;
    if (document.body.getAttribute('data-theme') !== 'dark') return rawColor;
    return ensureReadableOnDark(rawColor);
}

